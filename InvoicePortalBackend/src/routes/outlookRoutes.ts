import { Router } from 'express';
import { sincronizarBuzonController, sincronizarProveedorController } from '../controllers/outlookController';
import { requireAuth } from '../middlewares/authMiddleware';
import { requireArea } from '../middlewares/areaAccessMiddleware';
const router = Router();
router.use(requireAuth);
router.post('/sincronizar', requireArea('SISTEMAS'), sincronizarBuzonController);
router.post('/proveedores/:idProveedor/sincronizar', requireArea('SISTEMAS'), sincronizarProveedorController);
router.post('/sincronizar/:idProveedor', requireArea('SISTEMAS'), sincronizarProveedorController);
export default router;
